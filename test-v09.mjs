import assert from 'node:assert/strict';
import {TOOL_SCHEMAS,DIRECT_TOOLS,runTool} from './tools-v06-backend.js';
assert.equal(DIRECT_TOOLS.size,15);
assert.equal(TOOL_SCHEMAS.length,16);
for(const name of DIRECT_TOOLS)assert(TOOL_SCHEMAS.some(x=>x.function.name===name));
assert.equal(runTool('estimate_overtime_pay',{hours:60,hourly_rate:15}).grossPay,1050);
assert.equal(runTool('goal_timeline',{current_balance:3000,target_balance:10000,contribution_per_period:500}).periods,14);
assert.equal(runTool('date_offset',{date:'2026-11-15',days:30}).date,'2026-12-15');
assert.equal(runTool('work_shift_hours',{start:'22:00',end:'06:00',break_minutes:30}).paidHours,7.5);
assert.equal(runTool('split_expense',{subtotal:100,tip_percent:20,people:4}).perPerson,30);
assert.equal(runTool('text_statistics',{text:'hello world\nsecond line'}).words,4);
assert.equal(runTool('loan_payment',{principal:1200,annual_rate_percent:0,months:12}).monthlyPayment,100);
assert.equal(runTool('fuel_trip_estimate',{miles:200,mpg:20,price_per_gallon:3}).estimatedFuelCost,30);
assert.equal(runTool('budget_summary',{income:3000,fixed_costs:1000,variable_costs:500,planned_savings:1000}).remaining,500);
assert.equal(runTool('compound_growth',{principal:1000,annual_rate_percent:0,periods_per_year:12,years:1,deposit_per_period:100}).projectedBalance,2200);
assert(runTool('date_offset',{date:'2026-02-30',days:1}).error);
assert(runTool('work_shift_hours',{start:'25:00',end:'05:00',break_minutes:0}).error);
assert(runTool('loan_payment',{principal:100,annual_rate_percent:-1,months:12}).error);
assert(!DIRECT_TOOLS.has('propose_task'));
console.log('v0.9 suite: 15 direct tools, 16 AI schemas, 14 checks passed');
